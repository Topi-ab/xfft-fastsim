"""Builds the xfft stand-in's C engine (model/xfft_engine.c with model/xfft_dpi.c) for the current configuration
(XFFT_CONFIG) into <out dir>, for the SV wrapper (model/xfft_engine.sv, XSim and Verilator) and the VHDL wrapper
(model/xfft_engine.vhdl, NVC and GHDL). Needs a C compiler (gcc, or CC) and the C model of the generated core:
scripts/generate_ip.py runs Vivado once to generate it, after that the build needs no Vivado. Standard library
only.

    python scripts/build_engine.py <out dir>
    python scripts/build_engine.py --timing-only <out dir>

--timing-only (or XFFT_TIMING_ONLY=1): model/xfft_dpi_stub.c instead of model/xfft_dpi.c and AMD's C model, so
no Vivado and no generated core are needed. The timing is the same; every output sample is 0 and no frame
overflows (OVFLO 0). For timing tests where the data does not matter, such as CI.

Names: every name follows the configuration's module (model/xfft_config.py), so that different configurations
can share one simulation: for module xfft_core the package xfft_model_pkg, the library libxfft_engine.so and its
C functions xfft_engine_new, _step, _free, _wallclock; for any other module <module>_pkg, lib<module>_engine.so
and <module>_engine_new and so on (<pkg> and <lib> below).

Writes:
    <out dir>/<pkg>.sv              the configuration and its timing constants (model/xfft_timing.py) as an SV
                                    package; without measured constants it says so (XFFT_HAS_TIMING = 0), which
                                    is enough for the timing bench on the real core, not for the stand-in
    <out dir>/<pkg>.vhdl            the same constants as a VHDL package
    <out dir>/xfft_model.h          the same constants as a C header, compiled into the library
    <out dir>/<module>.sv           the SV and VHDL wrappers with the module's names (module or entity, package,
    <out dir>/<module>.vhdl         C functions), when the module is not xfft_core (else model/xfft_engine.sv and
                                    model/xfft_engine.vhdl are used as they are); named after the module, so
                                    that their compiled units do not collide with those of another wrapper
    <out dir>/cmodel/               AMD's bit-accurate C model: the generated core's cmodel output product,
                                    unzipped (not with --timing-only)
    <out dir>/xfft_cmodel_api.h     includes the C model's header and names its API prefix (both carry the IP
                                    version, read from the archive: model/cmodel_archive.py; not with
                                    --timing-only)
    <out dir>/<lib>                 the engine, exporting only its four functions (-fvisibility=hidden,
                                    -Bsymbolic; -DXFFT_ENGINE_PREFIX names them, model/xfft_engine.h)

The library finds the C model's libraries through its rpath $ORIGIN/cmodel, so <out dir> can be moved or copied
as a whole. It is rebuilt only when its sources, the constants, this script or the C-model archive change (stamp
file). The SV package names their digest, so a simulator build that hashes its sources sees a new library too.
Users: tests/sim_runner.py (DpiModel, FFT_MODEL=engine), tests/timing/xfft_timing_bench.py and the
characterization bench (characterize/bench/build_engine_char.py).
"""

from __future__ import annotations

import hashlib
import os
import shlex
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(REPO / "model"), str(REPO / "scripts")]
import cmodel_archive  # noqa: E402
import generate_ip  # noqa: E402
import xfft_config  # noqa: E402
import xfft_timing  # noqa: E402

MODEL = REPO / "model"
C_SOURCES = [MODEL / "xfft_engine.c", MODEL / "xfft_dpi.c"]
TIMING_ONLY_SOURCES = [MODEL / "xfft_engine.c", MODEL / "xfft_dpi_stub.c"]
C_HEADERS = [MODEL / "xfft_engine.h"]
SV_WRAPPER = MODEL / "xfft_engine.sv"
VHDL_WRAPPER = MODEL / "xfft_engine.vhdl"
# The C functions the wrappers call, by the names they have for module xfft_core
C_FUNCTIONS = ("new", "step", "free")
DEFAULT = xfft_config.XfftConfig()


def renamed(path: Path, cfg: xfft_config.XfftConfig, replacements: list[tuple[str, str]], comment: str) -> str:
    """The text of path with each replacement made (each must occur), headed by a comment that names its source."""
    text = path.read_text()
    for old, new in replacements:
        if old not in text:
            sys.exit(f"build_engine: {path.name} has no {old!r} to rename")
        text = text.replace(old, new)
    return (f"{comment} Generated by scripts/build_engine.py from model/{path.name}; do not edit.\n"
            f"{comment} Configuration {cfg.tag}.\n"
            f"{comment} In the comments below, module {DEFAULT.module}, package {DEFAULT.model_package}, "
            f"lib{DEFAULT.engine_prefix}.so and {DEFAULT.engine_prefix}_*\n"
            f"{comment} stand for {cfg.module}, {cfg.model_package}, lib{cfg.engine_prefix}.so and "
            f"{cfg.engine_prefix}_*.\n" + text)


def sv_wrapper(cfg: xfft_config.XfftConfig) -> str:
    """model/xfft_engine.sv with the configuration's names: the module (still `XFFT_ENGINE_NAME when that is
    defined), its package and the C names of the DPI-C imports."""
    header = ("`ifdef XFFT_ENGINE_NAME\nmodule `XFFT_ENGINE_NAME\n`elsif XFFT_CORE_NAME\nmodule `XFFT_CORE_NAME\n"
              "`else\nmodule xfft_core\n`endif\n")
    return renamed(SV_WRAPPER, cfg, [
        (header, f"`ifdef XFFT_ENGINE_NAME\nmodule `XFFT_ENGINE_NAME\n`else\nmodule {cfg.module}\n`endif\n"),
        (f"import {DEFAULT.model_package}::*;", f"import {cfg.model_package}::*;"),
        *((f'"DPI-C" {DEFAULT.engine_prefix}_{f} =', f'"DPI-C" {cfg.engine_prefix}_{f} =') for f in C_FUNCTIONS),
        (f'"%m: {DEFAULT.engine_prefix}_new failed"', f'"%m: {cfg.engine_prefix}_new failed"'),
    ], "//")


def vhdl_wrapper(cfg: xfft_config.XfftConfig) -> str:
    """model/xfft_engine.vhdl with the configuration's names: the entity, its package, the C functions of the
    foreign attributes, and the entity, the C functions and the library in the messages."""
    return renamed(VHDL_WRAPPER, cfg, [
        ("entity xfft_core is", f"entity {cfg.module} is"),
        ("architecture c_engine of xfft_core is", f"architecture c_engine of {cfg.module} is"),
        (f"use work.{DEFAULT.model_package}.all;", f"use work.{cfg.model_package}.all;"),
        *((f'"VHPIDIRECT {DEFAULT.engine_prefix}_{f}"', f'"VHPIDIRECT {cfg.engine_prefix}_{f}"')
          for f in C_FUNCTIONS if f != "free"),
        (f"lib{DEFAULT.engine_prefix}.so", f"lib{cfg.engine_prefix}.so"),
        (f'report "{DEFAULT.engine_prefix}_', f'report "{cfg.engine_prefix}_'),
        (f'report "{DEFAULT.module}: ', f'report "{cfg.module}: '),
        (f"{DEFAULT.engine_prefix}_new failed", f"{cfg.engine_prefix}_new failed"),
    ], "--")


def archive(cfg: xfft_config.XfftConfig) -> Path:
    """The C model of the configuration's core, generated with it; a clear message where that needs Vivado and
    Vivado is not there."""
    try:
        return cmodel_archive.find(generate_ip.generate(cfg))
    except cmodel_archive.CModelError as e:
        sys.exit(f"build_engine: {e}")
    except FileNotFoundError as e:
        sys.exit(f"build_engine: the C model of {cfg.tag} comes with the generated core, which needs Vivado once "
                 f"({e.filename} not found): run scripts/generate_ip.py where Vivado is installed, or copy its "
                 f"output {cfg.build_dir / 'ip_gen'} here")


def digest(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for p in paths:
        h.update(p.name.encode())
        h.update(p.read_bytes())
    return h.hexdigest()


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def timing_only_env() -> bool:
    return os.environ.get("XFFT_TIMING_ONLY", "").strip().lower() in ("1", "yes", "y", "on", "true")


def build(out: Path, timing_only: bool | None = None) -> None:
    """Build into out; timing_only (default: XFFT_TIMING_ONLY) links model/xfft_dpi_stub.c instead of the C model."""
    out = out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    timing_only = timing_only_env() if timing_only is None else timing_only
    cfg = xfft_config.current()
    try:
        timing = xfft_timing.constants(cfg)
    except LookupError:
        timing = None
    zip_path = None if timing_only else archive(cfg)
    sources = TIMING_ONLY_SOURCES if timing_only else C_SOURCES
    header = xfft_timing.c_header(cfg, timing)
    cc = shlex.split(os.environ.get("CC") or "gcc")
    # The constants are compiled in: the header is part of the digest, and so is the compiler
    prefix = f"-DXFFT_ENGINE_PREFIX={cfg.engine_prefix}"
    lib_digest = hashlib.sha256((digest([Path(__file__).resolve(), *([zip_path] if zip_path else []), *sources,
                                         *C_HEADERS])
                                 + header + " ".join(cc) + " " + prefix + (" timing-only" if timing_only else "")
                                 ).encode()).hexdigest()
    lib = out / f"lib{cfg.engine_prefix}.so"
    write_if_changed(out / f"{cfg.model_package}.sv", f"// {lib.name} sources: sha256 {lib_digest}\n"
                     + xfft_timing.sv_package(cfg, timing))
    write_if_changed(out / f"{cfg.model_package}.vhdl", xfft_timing.vhdl_package(cfg, timing))
    if cfg.module != xfft_config.DEFAULT_MODULE:
        write_if_changed(out / f"{cfg.module}.sv", sv_wrapper(cfg))
        write_if_changed(out / f"{cfg.module}.vhdl", vhdl_wrapper(cfg))
    write_if_changed(out / "xfft_model.h", header)

    stamp = out / "build_engine.sha256"
    if lib.exists() and stamp.exists() and stamp.read_text() == lib_digest:
        return
    if timing_only:
        compile_library(out, cc, [*cc, "-shared", "-fPIC", "-O2", "-std=gnu11", "-fvisibility=hidden", prefix,
                                       f"-I{out}", f"-I{MODEL}", *map(str, sources), "-o", str(lib),
                                       "-Wl,-Bsymbolic"])
        stamp.write_text(lib_digest)
        return
    try:
        names = cmodel_archive.names(zip_path)
    except cmodel_archive.CModelError as e:
        sys.exit(f"build_engine: {e}")
    cmodel = out / "cmodel"
    shutil.rmtree(cmodel, ignore_errors=True)
    with zipfile.ZipFile(zip_path) as z:
        z.extractall(cmodel)
    (out / "xfft_cmodel_api.h").write_text(
        f"// Generated by scripts/build_engine.py from {zip_path.name}; do not edit.\n"
        f"#include \"{names.header}\"\n#define XFFT_API_PREFIX {names.api_prefix}\n")
    # -fvisibility=hidden: only the engine's four functions are exported (xfft_dpi.c is compiled in, hidden), so
    # the library shares the process with the simulator, cocotb, Python and other configurations' libraries;
    # -Bsymbolic: its own calls stay inside it. --disable-new-dtags: DT_RPATH instead of DT_RUNPATH. DT_RPATH also
    # applies to the dependencies of dependencies, so the C model's own libraries in cmodel/ (gmp, mpfr, the
    # floating-point C model, whatever versions the archive has) are found without LD_LIBRARY_PATH, also in
    # cocotb's Python process.
    # $ORIGIN/cmodel: cmodel/ beside the library wherever the directory is (a snapshot restored elsewhere, a copy
    # in a run directory).
    cmd = [*cc, "-shared", "-fPIC", "-O2", "-std=gnu11", "-fvisibility=hidden", prefix, f"-I{out}", f"-I{cmodel}",
           f"-I{MODEL}", *map(str, sources), "-o", str(lib), f"-L{cmodel}", f"-l{names.library}", "-lm",
           "-Wl,-Bsymbolic", "-Wl,--disable-new-dtags", "-Wl,-rpath,$ORIGIN/cmodel"]
    compile_library(out, cc, cmd)
    stamp.write_text(lib_digest)


def compile_library(out: Path, cc: list[str], cmd: list[str]) -> None:
    """Run the compiler command cmd, its output into out/cc.log."""
    with open(out / "cc.log", "w") as log:
        log.write(" ".join(cmd) + "\n")
        log.flush()
        try:
            result = subprocess.run(cmd, cwd=out, stdout=log, stderr=subprocess.STDOUT)
        except FileNotFoundError:
            sys.exit(f"build_engine: C compiler {cc[0]} not found (set CC)")
    if result.returncode != 0:
        sys.exit(f"build_engine: {cc[0]} failed ({result.returncode}), see {out / 'cc.log'}")


if __name__ == "__main__":
    args = sys.argv[1:]
    only = "--timing-only" in args
    args = [a for a in args if a != "--timing-only"]
    if len(args) != 1:
        sys.exit(__doc__)
    build(Path(args[0]), timing_only=True if only else None)
