def test_simulator_parameters(monkeypatch, tmp_path):
    import hdl_sources

    import sim_runner

    monkeypatch.setattr(shutil, "which", lambda name: f"/usr/bin/{name}")       # every simulator installed
    monkeypatch.setattr(sim_runner, "SIM_IDENTITY", {})                       # no version check of a fake path
    sim_runner.installed.cache_clear()

    def skipped(params):
        return {p.values[0]: [m.kwargs.get("reason") for m in p.marks if m.name == "skip"] for p in params}

    assert skipped(hdl_sources.simulators("engine")) == {"vivado": [], "nvc": [], "ghdl": [], "verilator": [],
                                                         "riviera": []}
    monkeypatch.delenv("XFFT_RIVIERA_LIBS", raising=False)
    s = skipped(hdl_sources.simulators("rtl"))          # the encrypted core: XSim and Riviera only
    assert s["vivado"] == [] and all(r for r in (s["nvc"], s["ghdl"], s["verilator"]))
    assert "XFFT_RIVIERA_LIBS" in s["riviera"][0]       # Riviera needs AMD's libraries compiled for it
    monkeypatch.setenv("XFFT_RIVIERA_LIBS", str(tmp_path))
    assert skipped(hdl_sources.simulators("rtl"))["riviera"] == []
    s = skipped(hdl_sources.simulators("engine", xsim_only="a plain XSim bench"))
    assert s["vivado"] == [] and s["nvc"] == ["nvc: a plain XSim bench: XSim only"]
    assert s["verilator"] == ["verilator: a plain XSim bench: XSim only"]
    assert s["riviera"] == ["riviera: a plain XSim bench: XSim only"]
    monkeypatch.setattr(shutil, "which", lambda name: None)                    # none installed
    sim_runner.installed.cache_clear()
    params = hdl_sources.simulators("rtl")
    assert "skip" in [m.name for m in params[1].marks]           # the model's reason, also when not installed
    assert [m.name for m in params[0].marks] == ["skipif"] and params[0].marks[0].args[0]
    assert hdl_sources.toplevel_lang("engine", "vivado") == "verilog" == hdl_sources.toplevel_lang("engine",
                                                                                                 "verilator")
    assert hdl_sources.toplevel_lang("engine", "nvc") == "vhdl" == hdl_sources.toplevel_lang("rtl")
    assert hdl_sources.toplevel_lang("engine", "riviera") == "verilog"
    sim_runner.installed.cache_clear()                  # the next tests see the real PATH again


def test_fft_model(monkeypatch):
    """FFT_MODEL: rtl (default) or engine; the stand-in's earlier name cmodel is refused with a message naming
    engine."""
    import hdl_sources

    monkeypatch.delenv("FFT_MODEL", raising=False)
    assert hdl_sources.fft_model() == "rtl"
    monkeypatch.setenv("FFT_MODEL", "engine")
    assert hdl_sources.fft_model() == "engine"
    monkeypatch.setenv("FFT_MODEL", "cmodel")
    with pytest.raises(ValueError, match="FFT_MODEL=engine"):
        hdl_sources.fft_model()
    monkeypatch.setenv("FFT_MODEL", "other")
    with pytest.raises(ValueError, match="rtl, engine"):
        hdl_sources.fft_model()


def test_dpi_model_vhdl_side(tmp_path, monkeypatch):
    import sim_runner

    build = tmp_path / "build.py"
    build.write_text("import sys, pathlib\nout = pathlib.Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)\n"
                     "(out / 'pkg.vhdl').write_text('package p is end;')\n")
    wrapper = tmp_path / "core.vhdl"
    wrapper.write_text("entity core is end;")
    model = sim_runner.DpiModel(name="m", build=build, sources=(), inputs=(), vhdl_sources=("pkg.vhdl", wrapper))
    out = tmp_path / "dpi"
    monkeypatch.setenv("LD_PRELOAD", "/lib/other.so")
    hdl, env, link = model.prepare_vhdl(out, "nvc")
    assert hdl == [out / "pkg.vhdl", wrapper] and env == {"LD_PRELOAD": f"{out / 'libm.so'}:/lib/other.so"}
    assert link == []
    hdl, env, link = model.prepare_vhdl(out, "ghdl")
    assert env == {} and link[0] == f"-Wl,{out / 'libm.so'}" and any("rpath-link" in a for a in link)
    plain = sim_runner.DpiModel(name="m", build=build, sources=("a.sv",), inputs=())
    assert "vhdl_sources" not in plain.cache_entry(lambda p: {"path": str(p)})
    with pytest.raises(ValueError):
        plain.prepare_vhdl(out, "nvc")
    with pytest.raises(ValueError):
        model.prepare_verilator(out)            # no SV sources


def test_dpi_model_verilator_side(tmp_path):
    """Verilator: the SV sources, the library as a file argument with its rpath and the C model's -rpath-link."""
    import sim_runner

    build = tmp_path / "build.py"
    build.write_text("import sys, pathlib\nout = pathlib.Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)\n"
                     "(out / 'pkg.sv').write_text('package p; endpackage')\n")
    wrapper = tmp_path / "core.sv"
    model = sim_runner.DpiModel(name="m", build=build, sources=("pkg.sv", wrapper), inputs=())
    out = tmp_path / "dpi"
    hdl, args = model.prepare_verilator(out)
    assert hdl == [out / "pkg.sv", wrapper]
    assert args == [str(out / "libm.so"), "-LDFLAGS", f"-Wl,-rpath,{out} -Wl,-rpath-link,{out / 'cmodel'}"]
    assert "--threads" not in " ".join(args)


# ---- The engine itself, with a stand-in for the C model ----

STUB = r"""
#include <stdlib.h>
void* xfft_dpi_new(int nfft, int w, int tw, int r, int slots) { return calloc(1, 1); }
void xfft_dpi_free(void* h) { free(h); }
void xfft_dpi_put(void* h, int index, long long re, long long im) {}
int xfft_dpi_run(void* h, int slot, int fwd, int scale_sch) { return 0; }
long long xfft_dpi_get_re(void* h, int slot, int index) { return index; }
long long xfft_dpi_get_im(void* h, int slot, int index) { return -index; }
"""


def engine(tmp_path: Path, spec: str):
    if shutil.which("gcc") is None:
        pytest.skip("gcc not on PATH")
    cfg = xfft_config.parse(spec)
    (tmp_path / "xfft_model.h").write_text(xfft_timing.c_header(cfg, xfft_timing.constants(cfg)))
    (tmp_path / "stub.c").write_text(STUB)
    lib = tmp_path / "libengine.so"
    subprocess.run(["gcc", "-shared", "-fPIC", "-O1", "-Wall", "-Werror", f"-I{tmp_path}", f"-I{REPO / 'model'}",
                    str(REPO / "model" / "xfft_engine.c"), str(tmp_path / "stub.c"), "-o", str(lib)], check=True)
    so = ctypes.CDLL(str(lib))
    so.xfft_engine_step.argtypes = [ctypes.c_int32] * 13 + [ctypes.POINTER(ctypes.c_int32)]
    return cfg, so


@pytest.mark.parametrize("spec", TIMED)
def test_engine_latencies(tmp_path, spec):
    """One frame with valid and ready high throughout: tready RESET_TO_READY clocks after reset, the first and
    last output and the status word at the constants' clocks, the data in natural order with tlast on the last."""
    cfg, so = engine(tmp_path, spec)
    t = xfft_timing.constants(cfg)
    n = cfg.points
    eid = so.xfft_engine_new(cfg.nfft, cfg.input_width, cfg.twiddle_width, int(cfg.rounding == "convergent"),
                             cfg.config_width, cfg.data_width, cfg.user_width)
    assert eid >= 0
    assert so.xfft_engine_new(cfg.nfft + 1, cfg.input_width, cfg.twiddle_width, 1, cfg.config_width,
                              cfg.data_width, cfg.user_width) == -1
    out = (ctypes.c_int32 * XE_OUT_COUNT)()
    before = list(out)
    sent, first_in, ready_at, outs, status = 0, None, None, [], []
    for clock in range(t["LATENCY_LAST_OUT"] + 200):
        aresetn = int(clock >= 5)
        valid = int(aresetn and sent < n and ready_at is not None)
        so.xfft_engine_step(eid, aresetn, 0, 0, valid, sent & 0xFFFF, 0, 0, 0, 0, int(sent == n - 1), 1, 1, out)
        if valid and before[1]:
            first_in = clock if first_in is None else first_in
            sent += 1
        if before[8]:                                   # m_axis_data_tvalid before this edge: a handshake
            outs.append((clock, before[7], before[9], before[2]))
        if before[11]:
            status.append(clock)
        assert out[19] == 0
        before = list(out)
        if ready_at is None and out[0] and out[1]:
            ready_at = clock + 1                        # the first edge with tready high
    assert ready_at - 5 == t["RESET_TO_READY"]
    assert len(outs) == n and [u & ((1 << cfg.ovflo_bit) - 1) for _, u, _, _ in outs] == list(range(n))
    assert [last for _, _, last, _ in outs] == [0] * (n - 1) + [1]
    assert outs[0][0] - first_in == t["LATENCY_FIRST_OUT"] and outs[-1][0] - first_in == t["LATENCY_LAST_OUT"]
    assert status == [outs[-1][0] + t["STATUS_AFTER_LAST_OUT"]]
    so.xfft_engine_free(eid)
