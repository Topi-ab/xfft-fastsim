"""The C engine's single source of constants and its build glue: the SV package, VHDL package and C header that
model/xfft_timing.py writes hold the same values; the SV package's text is unchanged; the VHDL wrapper is renamed
for another module; the models and the test parameters per simulator. With gcc, the engine itself
(model/xfft_engine.c with a stand-in for the C model, through ctypes): its latencies are the timing constants. No
Vivado, no simulator.
"""

import ctypes
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "model"), str(REPO / "scripts"), str(REPO / "tests")]

import xfft_config  # noqa: E402
import xfft_timing  # noqa: E402

SPECS = ["", "nfft=8", "nfft=9,input_width=18,twiddle_width=18,rounding=truncation,clock_mhz=250",
         "nfft=16,input_width=34,twiddle_width=34", "module=my_fft"]
TIMED = ["", "nfft=8"]          # configurations with shipped constants
XE_OUT_COUNT = 20


def constants_of(cfg, timing):
    sv = dict(re.findall(r"localparam int XFFT_(\w+) = (-?\d+);", xfft_timing.sv_package(cfg, timing)))
    vhdl = dict(re.findall(r"constant XFFT_(\w+): integer := (-?\d+);", xfft_timing.vhdl_package(cfg, timing)))
    c = dict(re.findall(r"#define XFFT_(\w+) (-?\d+)", xfft_timing.c_header(cfg, timing)))
    return sv, vhdl, c


def timing_of(cfg):
    try:
        return xfft_timing.constants(cfg)
    except LookupError:
        return None


@pytest.mark.parametrize("spec", SPECS)
def test_three_tables_agree(spec):
    cfg = xfft_config.parse(spec)
    for timing in (timing_of(cfg), None):
        sv, vhdl, c = constants_of(cfg, timing)
        expected = {k: str(v) for k, v in xfft_timing.model_values(cfg, timing).items()}
        assert sv == vhdl == c == expected
        assert set(xfft_timing.NAMES) <= set(sv) and len(sv) == len(xfft_timing.NAMES) + 11


def test_sv_package_text_is_unchanged():
    """The SV package, as it has always been written (testbenches of users import it)."""
    cfg = xfft_config.parse("nfft=8")
    text = xfft_timing.sv_package(cfg, xfft_timing.constants(cfg))
    lines = text.splitlines()
    assert lines[0] == f"// Generated by model/xfft_timing.py for {cfg.tag}; do not edit."
    assert lines[1] == "package xfft_model_pkg;" and lines[-1] == "endpackage" and text.endswith("endpackage\n")
    assert lines[2] == "    localparam int XFFT_N = 256;"
    assert lines[13] == "    localparam int XFFT_LATENCY_FIRST_OUT = 627;"
    assert len(lines) == 3 + 11 + len(xfft_timing.NAMES)


