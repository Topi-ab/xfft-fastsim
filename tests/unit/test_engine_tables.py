# ---- The engine itself, with a stand-in for the C model ----

STUB = r"""
#include <stdlib.h>
void* xfft_dpi_new(int nfft, int w, int tw, int r, int slots) { return calloc(1, 1); }
void xfft_dpi_free(void* h) { free(h); }
void xfft_dpi_put(void* h, int index, long long re, long long im) {}
int xfft_dpi_run(void* h, int slot, int fwd, int scale_sch) { return 0; }
long long xfft_dpi_get_re(void* h, int slot, int index) { return index; }
long long xfft_dpi_get_im(void* h, int slot, int index) { return -index; }
"""


def engine(tmp_path: Path, spec: str):
    if shutil.which("gcc") is None:
        pytest.skip("gcc not on PATH")
    cfg = xfft_config.parse(spec)
    (tmp_path / "xfft_model.h").write_text(xfft_timing.c_header(cfg, xfft_timing.constants(cfg)))
    (tmp_path / "stub.c").write_text(STUB)
    lib = tmp_path / "libengine.so"
    subprocess.run(["gcc", "-shared", "-fPIC", "-O1", "-Wall", "-Werror", f"-I{tmp_path}", f"-I{REPO / 'model'}",
                    str(REPO / "model" / "xfft_engine.c"), str(tmp_path / "stub.c"), "-o", str(lib)], check=True)
    so = ctypes.CDLL(str(lib))
    so.xfft_engine_step.argtypes = [ctypes.c_int32] * 13 + [ctypes.POINTER(ctypes.c_int32)]
    return cfg, so


@pytest.mark.parametrize("spec", TIMED)
def test_engine_latencies(tmp_path, spec):
    """One frame with valid and ready high throughout: tready RESET_TO_READY clocks after reset, the first and
    last output and the status word at the constants' clocks, the data in natural order with tlast on the last."""
    cfg, so = engine(tmp_path, spec)
    t = xfft_timing.constants(cfg)
    n = cfg.points
    eid = so.xfft_engine_new(cfg.nfft, cfg.input_width, cfg.twiddle_width, int(cfg.rounding == "convergent"),
                             cfg.config_width, cfg.data_width, cfg.user_width)
    assert eid >= 0
    assert so.xfft_engine_new(cfg.nfft + 1, cfg.input_width, cfg.twiddle_width, 1, cfg.config_width,
                              cfg.data_width, cfg.user_width) == -1
    out = (ctypes.c_int32 * XE_OUT_COUNT)()
    before = list(out)
    sent, first_in, ready_at, outs, status = 0, None, None, [], []
    for clock in range(t["LATENCY_LAST_OUT"] + 200):
        aresetn = int(clock >= 5)
        valid = int(aresetn and sent < n and ready_at is not None)
        so.xfft_engine_step(eid, aresetn, 0, 0, valid, sent & 0xFFFF, 0, 0, 0, 0, int(sent == n - 1), 1, 1, out)
        if valid and before[1]:
            first_in = clock if first_in is None else first_in
            sent += 1
        if before[8]:                                   # m_axis_data_tvalid before this edge: a handshake
            outs.append((clock, before[7], before[9], before[2]))
        if before[11]:
            status.append(clock)
        assert out[19] == 0
        before = list(out)
        if ready_at is None and out[0] and out[1]:
            ready_at = clock + 1                        # the first edge with tready high
    assert ready_at - 5 == t["RESET_TO_READY"]
    assert len(outs) == n and [u & ((1 << cfg.ovflo_bit) - 1) for _, u, _, _ in outs] == list(range(n))
    assert [last for _, _, last, _ in outs] == [0] * (n - 1) + [1]
    assert outs[0][0] - first_in == t["LATENCY_FIRST_OUT"] and outs[-1][0] - first_in == t["LATENCY_LAST_OUT"]
    assert status == [outs[-1][0] + t["STATUS_AFTER_LAST_OUT"]]
    so.xfft_engine_free(eid)
